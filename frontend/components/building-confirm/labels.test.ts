import { describe, expect, it } from 'vitest';
import { floorFromUnit } from './labels';

describe('층 표기 정규화', () => {
  it.each([
    ['지하1층', '지하 1층'],
    ['지하 01 층', '지하 1층'],
    ['지1층', '지하 1층'],
    ['지 01층', '지하 1층'],
    ['B1', '지하 1층'],
    ['B01', '지하 1층'],
    ['b01', '지하 1층'],
    [' B 01 ', '지하 1층'],
    ['B1층', '지하 1층'],
    ['B01F', '지하 1층'],
    ['지하1층 101호', '지하 1층'],
    ['지1층101호', '지하 1층'],
    ['B01 101호', '지하 1층'],
    ['B02', '지하 2층'],
    ['b2f', '지하 2층'],
    ['1층', '1층'],
    ['지상 1층', '1층'],
    ['01층', '1층'],
    ['1F', '1층'],
    ['01f', '1층'],
    ['1층 101호', '1층'],
    ['1층101호', '1층'],
    ['4층 401호', '4층'],
  ])('%s를 %s로 표시한다', (input, expected) => {
    expect(floorFromUnit(input)).toBe(expected);
  });

  it.each([
    '',
    '1',
    '101호',
    '지하',
    '반지하',
    '모름',
    '아마 1층',
    '1층 또는 2층',
    '지하1층~지상1층',
    'B1/B2',
    'B00',
    '0층',
    '-1층',
    '1.5층',
    '1층 접근 우선 가정',
  ])('층을 확정할 수 없는 %s는 추측하지 않는다', (input) => {
    expect(floorFromUnit(input)).toBe('해당 층');
  });
});
