/** 실제 업종명도 키워드로 찾아 표시하고, 대응하지 않는 업종은 점포로 표시한다. */
export function industryEmoji(name: string): string {
  const rules: [RegExp, string][] = [
    [/네일|뷰티|미용|이용/, '💅'],
    [/무인|소매/, '🏪'],
    [/스튜디오|촬영|사진/, '📷'],
    [/세탁/, '🧺'],
    [/반려|동물/, '🐾'],
    [/고기|고깃|한식|음식점/, '🥩'],
    [/카페|커피|음료/, '☕'],
    [/베이커리|제과|빵/, '🥐'],
    [/노래/, '🎤'],
    [/헬스|체력|운동/, '🏋️'],
  ];
  // 반려동물 미용은 일반 미용보다 먼저 구분한다.
  if (/반려|동물/.test(name)) return '🐾';
  return rules.find(([pattern]) => pattern.test(name))?.[1] ?? '🏬';
}
